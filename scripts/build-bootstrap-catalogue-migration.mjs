import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const sources = [
  'catalogue/bootstrap/use-it-up.json',
  'catalogue/bootstrap/five-ingredient-weeknights.json',
  'catalogue/bootstrap/plant-forward-starters.json',
];

const statements = [];
for (const source of sources) {
  const payload = JSON.parse(await readFile(path.join(root, source), 'utf8'));
  payload.recipes = payload.recipes.map((recipe, position) => ({
    ...recipe,
    position,
    catalogue_batch: payload.book.slug,
    nutrition_provenance: Object.keys(recipe.nutrition ?? {}).length > 0 ? 'estimated' : 'unavailable',
    source_label: recipe.source_label ?? 'Kitchen Companion editorial recipe',
  }));
  const json = JSON.stringify(payload).replaceAll("'", "''");
  const bookSlug = payload.book.slug.replaceAll("'", "''");
  statements.push(`do $$
begin
  if not exists (select 1 from public.recipe_books where slug = '${bookSlug}') then
    perform private.import_catalogue_candidate_pack('${json}'::jsonb);
  end if;
end;
$$;`);
}

const output = path.join(root, 'supabase/migrations/20260828170000_seed_bootstrap_catalogue.sql');
await writeFile(output, `-- Generated by scripts/build-bootstrap-catalogue-migration.mjs. Do not edit by hand.\n${statements.join('\n')}\n`);
console.log(output);
